#!/usr/bin/env python3
"""Generate lib/src/data/islamic_umm_al_qura.g.dart.

The Umm al-Qura calendar is Saudi Arabia's official civil calendar. Its month
starts are published as a table by KACST; this script reads them from the
`hijridate` package (MIT), which ships that table for 1343-1500 AH.
The early years of that table contain 28- and 31-day months, so this table
starts at 1365 AH (1945), from where every month has 29 or 30 days.

Usage:
    pip install hijridate
    python3 tool/generate_umm_al_qura.py
"""
import datetime as dt
import os

from hijridate import Hijri

FIRST_YEAR, LAST_YEAR = 1365, 1500
EPOCH = dt.date(1970, 1, 1)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    days = [Hijri(year, month, 1).month_length()
            for year in range(FIRST_YEAR, LAST_YEAR + 1)
            for month in range(1, 13)]
    assert set(days) <= {29, 30}, "table has months that are not 29/30 days"
    lengths = "".join("1" if d == 30 else "0" for d in days)
    first = Hijri(FIRST_YEAR, 1, 1).to_gregorian()
    first = dt.date(first.year, first.month, first.day)
    out = [
        "// GENERATED by tool/generate_umm_al_qura.py — do not edit by hand.",
        f"// Umm al-Qura month starts, {FIRST_YEAR} AH ({first}) to the end of",
        f"// {LAST_YEAR} AH.",
        "",
        f"const int firstHijriYear = {FIRST_YEAR};",
        "const int firstHijriMonth = 1;",
        f"const int firstEpochDay = {(first - EPOCH).days}; // {first}",
        "",
        "/// One character per month: '1' = 30 days, '0' = 29 days.",
        "const String monthLengths =",
    ]
    for i in range(0, len(lengths), 60):
        end = ";" if i + 60 >= len(lengths) else ""
        out.append(f"    '{lengths[i:i + 60]}'{end}")
    path = os.path.join(ROOT, "lib", "src", "data", "islamic_umm_al_qura.g.dart")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {path}: {len(lengths)} months from {first}")


if __name__ == "__main__":
    main()
